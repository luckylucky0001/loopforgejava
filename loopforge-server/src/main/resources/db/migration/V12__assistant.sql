-- Iteration 11: conversations with the platform assistant (Main Bot).
CREATE TABLE assistant_sessions (
    id               VARCHAR(64)   NOT NULL PRIMARY KEY,
    project_id       VARCHAR(200)  REFERENCES projects (id) ON DELETE CASCADE,
    owner_id         VARCHAR(64)   REFERENCES users (id) ON DELETE CASCADE,
    status           VARCHAR(16)   NOT NULL,
    turn_started_at  TIMESTAMP WITH TIME ZONE,
    payload          VARCHAR       NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_assistant_sessions_owner ON assistant_sessions (owner_id, updated_at);
CREATE INDEX idx_assistant_sessions_project ON assistant_sessions (project_id, updated_at);

CREATE TABLE assistant_messages (
    seq         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id  VARCHAR(64)   NOT NULL REFERENCES assistant_sessions (id) ON DELETE CASCADE,
    payload     VARCHAR       NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_assistant_messages_session ON assistant_messages (session_id, seq);
