-- Iteration 13: history of SOP and role definitions (every write is a revision that can be
-- restored), and the executions of scheduled runs.
CREATE TABLE definition_revisions (
    kind        VARCHAR(16)   NOT NULL,
    entity_id   VARCHAR(200)  NOT NULL,
    revision    INTEGER       NOT NULL,
    name        VARCHAR(500),
    author      VARCHAR(200),
    summary     VARCHAR(1000),
    payload     VARCHAR       NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_definition_revisions PRIMARY KEY (kind, entity_id, revision)
);

CREATE TABLE schedule_executions (
    seq          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id  VARCHAR(64)   NOT NULL REFERENCES schedules (id) ON DELETE CASCADE,
    project_id   VARCHAR(200)  NOT NULL,
    trigger_kind VARCHAR(16)   NOT NULL,
    status       VARCHAR(16)   NOT NULL,
    run_id       VARCHAR(64),
    error        VARCHAR(2000),
    actor        VARCHAR(200),
    fired_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_schedule_executions ON schedule_executions (schedule_id, seq);
