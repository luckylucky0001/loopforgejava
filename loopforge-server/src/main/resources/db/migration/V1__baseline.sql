-- LoopForge4J baseline schema. Portable across H2 (dev/test) and PostgreSQL (production).
-- Definitions and run state are stored as JSON documents (same shape as the upstream
-- LoopForge payload columns); frequently filtered fields are mirrored into indexed columns.

CREATE TABLE workflows (
    id          VARCHAR(200)  NOT NULL PRIMARY KEY,
    name        VARCHAR(500)  NOT NULL,
    status      VARCHAR(32)   NOT NULL,
    revision    INTEGER       NOT NULL,
    payload     VARCHAR       NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE agents (
    id          VARCHAR(200)  NOT NULL PRIMARY KEY,
    name        VARCHAR(500)  NOT NULL,
    payload     VARCHAR       NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE runs (
    id             VARCHAR(64)   NOT NULL PRIMARY KEY,
    workflow_id    VARCHAR(200)  NOT NULL,
    status         VARCHAR(32)   NOT NULL,
    parent_run_id  VARCHAR(64),
    revision       BIGINT        NOT NULL,
    payload        VARCHAR       NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_runs_status ON runs (status);
CREATE INDEX idx_runs_workflow ON runs (workflow_id, created_at);
CREATE INDEX idx_runs_parent ON runs (parent_run_id);
CREATE INDEX idx_runs_created ON runs (created_at);

CREATE TABLE run_events (
    seq         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id      VARCHAR(64)   NOT NULL REFERENCES runs (id) ON DELETE CASCADE,
    node_id     VARCHAR(200),
    category    VARCHAR(64)   NOT NULL,
    type        VARCHAR(128)  NOT NULL,
    level       VARCHAR(16)   NOT NULL,
    message     VARCHAR,
    attributes  VARCHAR,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_run_events_run ON run_events (run_id, seq);

CREATE TABLE run_artifacts (
    id          VARCHAR(64)   NOT NULL PRIMARY KEY,
    seq         BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    run_id      VARCHAR(64)   NOT NULL REFERENCES runs (id) ON DELETE CASCADE,
    node_id     VARCHAR(200)  NOT NULL,
    attempt     INTEGER       NOT NULL,
    name        VARCHAR(300)  NOT NULL,
    path        VARCHAR(1000) NOT NULL,
    media_type  VARCHAR(200)  NOT NULL,
    size_bytes  BIGINT        NOT NULL,
    sha256      CHAR(64)      NOT NULL,
    content     VARCHAR,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_run_artifacts_run ON run_artifacts (run_id, seq);
