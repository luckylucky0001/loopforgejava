package io.github.loopforge4j.core.runtime.materialize;

import io.github.loopforge4j.core.domain.AgentHook;
import io.github.loopforge4j.core.domain.ExecutionScope;
import java.nio.file.Path;

/**
 * POSIX shell wrapper around a role hook (upstream uses a Python wrapper): passes the CLI's hook
 * payload to the script, runs it once or per repository and appends start/finish observations to
 * {@code $LOOPFORGE_HOOK_OUTPUT}, which the executor turns into run telemetry.
 */
final class HookWrapper {

    private HookWrapper() {}

    static String script(AgentHook hook, String interpreter, Path script) {
        String scope = hook.effectiveScope() == ExecutionScope.REPOSITORIES ? "repositories" : "run";
        return """
                #!/bin/sh
                # Generated by LoopForge4J for hook %1$s; edits are overwritten.
                hook_id=%2$s
                hook_event=%3$s
                scope=%4$s
                interp=%5$s
                script=%6$s
                out="${LOOPFORGE_HOOK_OUTPUT:-}"
                ws="${LOOPFORGE_WORKSPACE:-$(pwd)}"
                input=$(mktemp "${TMPDIR:-/tmp}/lf-hook.XXXXXX") || exit 1
                trap 'rm -f "$input"' EXIT
                cat > "$input"
                now() {
                  t=$(date +%%s%%3N 2>/dev/null)
                  case "$t" in ''|*N*) echo $(( $(date +%%s) * 1000 )) ;; *) echo "$t" ;; esac
                }
                note() {
                  [ -n "$out" ] || return 0
                  printf '{"hookId":"%%s","event":"%%s","phase":"%%s","exitCode":%%s,"durationMs":%%s,"repository":"%%s"}\\n' \\
                    "$hook_id" "$hook_event" "$1" "$2" "$3" "$4" >> "$out"
                }
                run_one() {
                  dir="$1"
                  note start null null "$dir"
                  started=$(now)
                  if [ -n "$dir" ]; then
                    ( cd "$ws/$dir" && LOOPFORGE_REPOSITORY_DIR="$dir" LOOPFORGE_EXECUTION_SCOPE=repositories \\
                        "$interp" "$script" < "$input" > /dev/null )
                  else
                    LOOPFORGE_EXECUTION_SCOPE=run "$interp" "$script" < "$input"
                  fi
                  code=$?
                  note finish "$code" $(( $(now) - started )) "$dir"
                  return $code
                }
                if [ "$scope" = repositories ]; then
                  if [ -z "${LOOPFORGE_REPOSITORY_DIRS:-}" ]; then
                    echo "repository-scoped hook requires at least one bound repository" >&2
                    note finish 2 0 ""
                    exit 2
                  fi
                  status=0
                  old_ifs=$IFS
                  IFS='
                '
                  set -f
                  for dir in $LOOPFORGE_REPOSITORY_DIRS; do
                    IFS=$old_ifs
                    run_one "$dir" || { status=$?; break; }
                  done
                  IFS=$old_ifs
                  exit $status
                fi
                run_one ""
                """.formatted(
                        hook.id(), quote(hook.id()), quote(hook.event()), scope, interpreter, quote(script.toString()));
    }

    /** Single-quotes a value for POSIX sh. */
    static String quote(String value) {
        return "'" + value.replace("'", "'\\''") + "'";
    }
}
